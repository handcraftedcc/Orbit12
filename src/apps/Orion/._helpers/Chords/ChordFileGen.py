def load_repo_lists():
    src = urllib.request.urlopen(URL).read().decode("utf-8")
    tree = ast.parse(src)

    result = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            name = node.targets[0].id if isinstance(node.targets[0], ast.Name) else None
            if name in ("prog_maj", "prog_min", "prog_modal"):
                result[name] = ast.literal_eval(node.value)

    return result


def parse_symbol(sym):
    accidental = 0

    if sym.startswith("b"):
        accidental = -1
        sym = sym[1:]
    elif sym.startswith("#"):
        accidental = 1
        sym = sym[1:]

    m = re.match(r"([ivIV]+)(.*)$", sym)
    if not m:
        raise ValueError("Could not parse chord symbol: " + sym)

    roman_raw, suffix = m.groups()
    degree = ROMAN_TO_DEGREE[roman_raw.upper()]

    if roman_raw.islower() and suffix == "":
        suffix = "m"

    if roman_raw.islower() and suffix in ("6", "7", "9", "69"):
        suffix = "m" + suffix

    if suffix not in SHAPES:
        raise ValueError(f"Unknown suffix {suffix!r} from symbol {sym!r}")

    return degree, accidental, SHAPES[suffix]


def line_to_chords(line):
    left = line.split("=", 1)[0].strip()
    symbols = left.split()

    out = []
    seen = set()

    for sym in symbols:
        chord = parse_symbol(sym)

        if chord not in seen:
            seen.add(chord)
            out.append(chord)

    return out


def rotate_shape(shape, inversion):
    notes = list(shape)

    for _ in range(inversion):
        notes.append(notes.pop(0) + 12)

    return tuple(notes)


def make_12_pad_bank(chords):
    pads = []
    inv = 0

    while len(pads) < PADS_PER_BANK:
        for degree, accidental, shape in chords:
            if len(pads) >= PADS_PER_BANK:
                break

            inv_shape = rotate_shape(shape, inv)
            pads.append((degree, accidental, inv_shape))

        inv += 1

    return tuple(pads)


def intern_bank(bank, chord_ids, chord_table):
    encoded = []

    for chord in bank:
        if chord not in chord_ids:
            chord_ids[chord] = len(chord_table)
            chord_table.append(chord)

        cid = chord_ids[chord]
        if cid > 255:
            raise RuntimeError("Too many unique pad chords for 1-byte IDs.")

        encoded.append(cid)

    return bytes(encoded)


def convert_all(lists):
    chord_ids = {}
    chord_table = []

    banks = []
    bank_seen = set()
    ranges = {}

    for list_name in ("prog_maj", "prog_min", "prog_modal"):
        start = len(banks)

        for line in lists[list_name]:
            chords = line_to_chords(line)
            bank = make_12_pad_bank(chords)

            if bank in bank_seen:
                continue

            bank_seen.add(bank)
            banks.append(intern_bank(bank, chord_ids, chord_table))

        end = len(banks)
        ranges[list_name] = (start, end)

    return chord_table, banks, ranges


def emit_tuple_bytes(name, values):
    lines = [f"{name} = ("]
    for b in values:
        lines.append(f"    {repr(b)},")
    lines.append(")")
    return "\n".join(lines)


