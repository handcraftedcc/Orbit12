def main():
    lists = load_repo_lists()
    chord_table, banks, ranges = convert_all(lists)

    output = emit_output(chord_table, banks, ranges)

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with OUT_FILE.open("w", encoding="utf-8") as f:
        f.write(output)

    print("Generated:", OUT_FILE)
    print("Unique pad chords:", len(chord_table))
    print("Unique 12-pad banks:", len(banks))
    print("Major banks:", ranges["prog_maj"])
    print("Minor banks:", ranges["prog_min"])
    print("Modal banks:", ranges["prog_modal"])


if __name__ == "__main__":
    main()