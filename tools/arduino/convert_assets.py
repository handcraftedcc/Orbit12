#!/usr/bin/env python3
"""Convert the checked-in Orion BMP assets to deterministic C++ byte arrays."""
import argparse
from pathlib import Path

ASSETS = ("ChainNav_12x5.1.bmp", "ChainNav_12x5.bmp", "ChainPreview_3x3.bmp",
          "Font_6x6.bmp", "LaunchScreen1.1.bmp", "StateIndicators_7x5.bmp")

def emit(source: Path, target: Path, check: bool = False) -> None:
    rows = ["// Generated by tools/arduino/convert_assets.py; do not edit.", "#pragma once", "#include <cstddef>", "#include <cstdint>", "namespace orbit::assets {"]
    for name in ASSETS:
        data = (source / name).read_bytes()
        symbol = "bmp_" + "".join(c.lower() if c.isalnum() else "_" for c in name.rsplit(".", 1)[0])
        rows += [f"inline constexpr std::uint8_t {symbol}[] = {{"]
        for pos in range(0, len(data), 16):
            rows.append("  " + ", ".join(f"0x{b:02x}" for b in data[pos:pos+16]) + ",")
        rows += ["};", f"inline constexpr std::size_t {symbol}_size = sizeof({symbol});"]
    rows.append("}  // namespace orbit::assets")
    rendered = "\n".join(rows) + "\n"
    if check:
        if target.read_text(encoding="ascii") != rendered:
            raise SystemExit(f"Generated assets differ from source: {target}")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(rendered, encoding="ascii", newline="\n")

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", nargs="?", type=Path, default=Path("circuitpython-source/src/apps/Orion/imgs"))
    parser.add_argument("target", nargs="?", type=Path, default=Path("firmware/Orbit12/src/platform/macropad/orion_assets.hpp"))
    parser.add_argument("--check", action="store_true", help="Verify exact regeneration without rewriting")
    args = parser.parse_args()
    emit(args.source, args.target, args.check)

if __name__ == "__main__":
    main()
