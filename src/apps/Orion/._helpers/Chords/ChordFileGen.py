def chord_notes_from_id(chord_id, key_root=0, octave=4):
    degree, accidental, intervals = CHORDS[chord_id]
    root = octave * 12 + key_root + DEGREE_OFFSETS[degree] + accidental
    return tuple(root + i for i in intervals)


def pad_notes(bank, pad_index, key_root=0, octave=4):
    chord_id = bank[pad_index]
    return chord_notes_from_id(chord_id, key_root, octave)


